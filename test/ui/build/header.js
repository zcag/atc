const { chromium } = require('playwright-core');
const exe = process.env.CHROME_BIN;
const base = process.argv[2] || 'http://127.0.0.1:7299';
const sid = process.argv[3];
const OUT = __dirname + '/../../shots/build/';
const ok = (c, m) => console.log(c ? 'ok  ' : 'FAIL', m);
(async () => {
  const b = await chromium.launch({ executablePath: exe });
  for (const scheme of ['light', 'dark']) {
    const ctx = await b.newContext({ viewport: { width: 1400, height: 900 }, colorScheme: scheme });
    await ctx.addInitScript(() => { try { localStorage.setItem('atc.notifask', '1'); } catch {} });
    const p = await ctx.newPage();
    const errs = [];
    p.on('pageerror', (e) => errs.push(e.message));
    p.on('frameattached', () => {});
    await p.route('**/api/**', (r) => r.request().method() === 'GET' ? r.continue() : r.fulfill({ status: 204 }));
    await p.goto(`${base}/#/s/${sid}`);
    await p.waitForTimeout(3500);
    ok(await p.isVisible('.hd h1'), `${scheme}: header title`);
    ok(!(await p.isVisible('.xterm')), `${scheme}: transcript is the default`);
    await p.screenshot({ path: `${OUT}s2c-read-1400-${scheme}.png` });
    await p.click('.hd h1');
    await p.keyboard.press('Backslash');
    await p.waitForTimeout(800);
    ok(await p.isVisible('.statep'), `${scheme}: backslash opens State`);
    await p.screenshot({ path: `${OUT}s2c-state-1400-${scheme}.png` });
    await p.keyboard.press('Backslash');
    await p.keyboard.press('Backquote');
    await p.waitForTimeout(800);
    ok(await p.isVisible('.xterm'), `${scheme}: backtick opens the terminal`);
    await p.screenshot({ path: `${OUT}s2c-term-1400-${scheme}.png` });
    await p.click('.hd h1');
    await p.keyboard.press('Backquote');
    await p.waitForTimeout(300);
    ok(!(await p.isVisible('.xterm')), `${scheme}: backtick returns to the transcript`);
    await p.click('.hd h1');
    await p.keyboard.press('x');
    await p.waitForTimeout(200);
    ok(await p.isVisible('.hd .more .sheet'), `${scheme}: x opens the session menu`);
    await p.keyboard.press('Escape');
    ok(!errs.length, `${scheme}: no page errors ` + errs.join(' | '));
    await ctx.close();
    const ph = await b.newContext({ viewport: { width: 400, height: 860 }, colorScheme: scheme, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
    const q = await ph.newPage();
    await q.route('**/api/**', (r) => r.request().method() === 'GET' ? r.continue() : r.fulfill({ status: 204 }));
    await q.goto(`${base}/#/s/${sid}`);
    await q.waitForTimeout(3500);
    await q.screenshot({ path: `${OUT}s2c-read-400-${scheme}.png` });
    await q.tap('.hd .l2');
    await q.waitForTimeout(800);
    ok(await q.isVisible('.statesheet'), `${scheme} phone: tapping the status line opens State`);
    await q.screenshot({ path: `${OUT}s2c-state-400-${scheme}.png` });
    await ph.close();
  }
  await b.close();
})();
