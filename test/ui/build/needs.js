const { chromium } = require('/home/user/proj/ui-kit/node_modules/playwright-core');
const { fakeSessions, needsIn } = require('./fake.js');
const exe = '/home/user/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome';
const base = process.argv[2] || 'http://127.0.0.1:7299';
const OUT = __dirname + '/../../shots/build/';
const ok = (c, m) => console.log(c ? 'ok  ' : 'FAIL', m);
const stub = (p) => p.route(/\/api\/(?!events)/, (r) => r.request().method() === 'GET' ? r.continue() : r.fulfill({ status: 204 }));
const fake = (list) => needsIn(list, 2, ['shop', 'dotfiles', 'notes', 'board', 'acme']);
(async () => {
  const b = await chromium.launch({ executablePath: exe });
  for (const scheme of ['light', 'dark']) {
    const ctx = await b.newContext({ viewport: { width: 1400, height: 900 }, colorScheme: scheme });
    await ctx.addInitScript(() => { try { localStorage.setItem('atc.notifask', '1'); localStorage.removeItem('atc.project'); } catch {} });
    const p = await ctx.newPage();
    const errs = [];
    p.on('pageerror', (e) => errs.push(e.message));
    await stub(p);
    await fakeSessions(p, base, fake);
    await p.goto(base + '/');
    await p.waitForTimeout(3000);
    ok(await p.locator('.bays .cn.n').count() >= 5, `${scheme}: amber need counts in the bay bar`);
    ok(await p.locator('.bgrp.waiting .brow').count() >= 5, `${scheme}: board groups what needs you first`);
    await p.locator('.bgrp.waiting .brow').first().click({ position: { x: 600, y: 10 } });
    await p.waitForTimeout(300);
    ok(await p.isVisible('.bexp .ask.compact'), `${scheme}: an opened needs row carries its ask`);
    await p.screenshot({ path: `${OUT}s4-needs-1400-${scheme}.png` });
    await p.keyboard.press('Escape');
    const bays = await p.locator('.bays .bay[data-bay]').count();
    await p.click('.bhead h1');
    await p.keyboard.press('1');
    await p.waitForTimeout(700);
    ok(await p.evaluate(() => location.hash.startsWith('#/s/')), `${scheme}: 1 opens bay 1's session`);
    const first = await p.evaluate(() => location.hash);
    await p.click('.hd h1');
    await p.keyboard.press('j');
    await p.waitForTimeout(700);
    ok((await p.evaluate(() => location.hash)) !== first, `${scheme}: j opens the next session in the bay`);
    await p.click('.hd h1');
    await p.keyboard.press('k');
    await p.waitForTimeout(700);
    ok((await p.evaluate(() => location.hash)) === first, `${scheme}: k goes back`);
    if (bays > 1) {
      await p.keyboard.press('2');
      await p.waitForTimeout(700);
      ok((await p.locator('.bays .bay.on .bn .n').innerText()) === (await p.locator('.bays .bay[data-bay]').nth(1).getAttribute('data-bay')), `${scheme}: 2 switches to bay 2`);
    }
    ok(!errs.length, `${scheme}: no page errors ` + errs.join(' | '));
    await ctx.close();
    const ph = await b.newContext({ viewport: { width: 400, height: 860 }, colorScheme: scheme, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
    await ph.addInitScript(() => { try { localStorage.setItem('atc.project', 'atc'); } catch {} });
    const q = await ph.newPage();
    await stub(q);
    await fakeSessions(q, base, fake);
    await q.goto(base + '/');
    await q.waitForTimeout(3000);
    ok(await q.isVisible('.offneeds'), `${scheme} phone: +N need you for bays out of view`);
    await q.tap('.offneeds');
    await q.waitForTimeout(400);
    ok(await q.isVisible('.peeksheet'), `${scheme} phone: it opens every bay's asks`);
    await q.screenshot({ path: `${OUT}s4-allneeds-400-${scheme}.png` });
    await q.locator('.peeksheet .pk .ti').last().tap();
    await q.waitForTimeout(800);
    ok(await q.isVisible('.sstrip'), `${scheme} phone: a session shows its bay's sessions as a strip`);
    const before = await q.evaluate(() => location.hash);
    await q.locator('.sstrip button:not(.on)').first().tap();
    await q.waitForTimeout(600);
    ok((await q.evaluate(() => location.hash)) !== before, `${scheme} phone: one tap switches session`);
    await q.screenshot({ path: `${OUT}s4-strip-400-${scheme}.png` });
    await ph.close();
  }
  await b.close();
})();
