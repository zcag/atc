const { chromium } = require('/home/user/proj/ui-kit/node_modules/playwright-core');
const exe = '/home/user/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome';
const base = process.argv[2] || 'http://127.0.0.1:7299';
const ok = (c, m) => console.log(c ? 'ok  ' : 'FAIL', m);
(async () => {
  const b = await chromium.launch({ executablePath: exe });
  const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.route('**/api/**', (r) => r.request().method() === 'GET' ? r.continue() : r.fulfill({ status: 204 }));
  await p.goto(base + '/');
  await p.waitForTimeout(2500);
  const bays = await p.locator('.bays .bay[data-bay]').count();
  ok(bays >= 2, `bay bar lists ${bays} bays`);
  await p.keyboard.press('2');
  await p.waitForTimeout(400);
  const second = await p.locator('.bays .bay[data-bay]').nth(1).locator('.bn .n').innerText();
  ok((await p.locator('.bays .bay.on .bn .n').innerText()) === second, `alt 2 selects ${second}`);
  ok((await p.locator('.side > .ph b').innerText()) === second, 'pane head names the bay');
  await p.keyboard.press('0');
  await p.waitForTimeout(300);
  ok((await p.locator('.bays .bay.on .bn .n').innerText()) === 'All', '0 is every bay');
  await p.keyboard.press('1');
  await p.waitForTimeout(600);
  const inSession = await p.evaluate(() => location.hash.startsWith('#/s/'));
  if (inSession) {
    await p.click('.side > .ph b');
    ok(await p.isVisible('.side'), 'session view shows the sessions pane');
    await p.keyboard.press('[');
    await p.waitForTimeout(200);
    ok(!(await p.isVisible('.side')), '[ hides the sessions pane');
    await p.keyboard.press('[');
    await p.waitForTimeout(200);
    ok(await p.isVisible('.side'), '[ brings it back');
    await p.keyboard.press('b');
    await p.waitForTimeout(300);
    ok((await p.evaluate(() => location.hash)) === '#/' || (await p.evaluate(() => location.hash)) === '', 'b goes to the board');
    await p.keyboard.press('s');
    await p.waitForTimeout(500);
    ok(await p.evaluate(() => location.hash.startsWith('#/s/')), 's comes back to the bay\'s session');
  } else console.log('note: bay 1 has no session to open');
  await p.click('.side > .ph b');
  await p.keyboard.press('?');
  await p.waitForTimeout(200);
  ok(await p.isVisible('.keys-ov'), '? opens the keys');
  await p.keyboard.press('Escape');
  await p.waitForTimeout(200);
  ok(!(await p.isVisible('.keys-ov')), 'esc closes the keys');
  await p.keyboard.press('/');
  await p.waitForTimeout(300);
  ok(await p.evaluate(() => !!document.querySelector('.pal[role=dialog]')), '/ opens the palette');
  await p.keyboard.press('Escape');
  ok(await p.isVisible('.console'), 'console line on desktop');
  ok(!errs.length, 'no page errors ' + errs.join(' | '));
  await p.setViewportSize({ width: 400, height: 860 });
  await p.waitForTimeout(300);
  ok(await p.isVisible('.tabbar') && !(await p.isVisible('.console')), 'phone: tab bar, no console');
  await b.close();
})();
