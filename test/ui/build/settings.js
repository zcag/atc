const { chromium } = require('playwright-core');
const exe = process.env.CHROME_BIN;
const base = process.argv[2] || 'http://127.0.0.1:7299';
const ok = (c, m) => console.log(c ? 'ok  ' : 'FAIL', m);
(async () => {
  const b = await chromium.launch({ executablePath: exe });
  const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.route('**/api/**', (r) => r.request().method() === 'GET' ? r.continue() : r.fulfill({ status: 204 }));
  await p.goto(base + '/');
  await p.waitForTimeout(2500);
  await p.keyboard.press(',');
  await p.waitForTimeout(300);
  ok(await p.isVisible('.settings'), ', opens settings');
  ok((await p.evaluate(() => location.hash)) === '#/settings', 'route is #/settings');
  ok((await p.locator('.thcard').count()) === 3, 'three theme cards');
  ok(await p.evaluate(() => getComputedStyle(document.querySelector('.pv .h')).getPropertyValue('--p-needs').trim().length > 0), 'previews carry theme colors');
  await p.click('.seg[aria-label="Typeface"] button:has-text("Recursive")');
  ok(await p.evaluate(() => JSON.parse(localStorage.getItem('atc.tx.prefs')).face === 'sans'), 'typeface saved');
  ok(await p.evaluate(() => document.querySelector('.rsample').style.fontFamily.includes('--sans')), 'sample follows typeface');
  await p.click('.seg[aria-label="Typeface"] button:has-text("Literata")');
  await p.click('.thcard:nth-child(3)');
  ok(await p.evaluate(() => document.documentElement.dataset.theme === 'nord'), 'picking Nord applies it (PUT stubbed)');
  ok(await p.evaluate(() => document.querySelector('.thcard:nth-child(3)').getAttribute('aria-checked') === 'true'), 'Nord card checked');
  await p.click('.thcard:nth-child(1)');
  await p.keyboard.press('Escape');
  await p.waitForTimeout(300);
  ok(!(await p.isVisible('.settings')), 'Esc closes');
  await p.keyboard.press('Control+k');
  await p.keyboard.type('settings');
  await p.waitForTimeout(300);
  ok(await p.evaluate(() => document.body.innerText.includes('Settings')), 'palette lists Settings');
  ok(!errs.length, 'no page errors ' + errs.join(' | '));
  await b.close();
})();
