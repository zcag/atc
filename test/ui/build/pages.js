const { chromium } = require('/home/user/proj/ui-kit/node_modules/playwright-core');
const exe = '/home/user/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome';
const base = process.argv[2] || 'http://127.0.0.1:7299';
const bay = process.argv[3] || 'atc';
const OUT = __dirname + '/../../shots/build/';
const ok = (c, m) => console.log(c ? 'ok  ' : 'FAIL', m);
const stub = (p) => p.route('**/api/**', (r) => r.request().method() === 'GET' ? r.continue() : r.fulfill({ status: 204 }));
const hash = (p) => p.evaluate(() => decodeURIComponent(location.hash));
(async () => {
  const b = await chromium.launch({ executablePath: exe });
  for (const scheme of ['light', 'dark']) {
    const ctx = await b.newContext({ viewport: { width: 1400, height: 900 }, colorScheme: scheme });
    await ctx.addInitScript(() => { try { localStorage.setItem('atc.notifask', '1'); } catch {} });
    const p = await ctx.newPage();
    const errs = [];
    p.on('pageerror', (e) => (e.stack || '').includes('/api/sessions/') || errs.push(e.message));
    await stub(p);
    await p.goto(`${base}/#/pages`);
    await p.waitForTimeout(2500);
    ok((await hash(p)).startsWith('#/g/'), `${scheme}: #/pages lands on #/g/<bay>`);
    ok(await p.isVisible('.pgv') && await p.isVisible('.bays'), `${scheme}: Pages sits inside the shell, under the bay bar`);
    ok(await p.locator('.views .kb.on', { hasText: 'Pages' }).count() === 1, `${scheme}: the view switch marks Pages`);
    await p.goto(`${base}/#/g/${bay}`);
    await p.waitForTimeout(3000);
    const rows = await p.locator('.pgi').count();
    ok(rows > 0, `${scheme}: index lists ${rows} pages of ${bay}`);
    ok(await p.isVisible('.pghd h1') && await p.locator('.pgread .pgbody2 > *').count() > 0, `${scheme}: the newest page opens beside the index`);
    ok(await p.locator('.pgidx img, .pgidx iframe').count() === 0, `${scheme}: no thumbnails`);
    await p.waitForTimeout(1500);
    await p.screenshot({ path: `${OUT}pages-1400-${scheme}.png` });
    await p.keyboard.press('j');
    await p.waitForTimeout(400);
    const h1 = await hash(p);
    ok(h1.split('/').length > 3, `${scheme}: j opens the next page (${h1.slice(0, 60)})`);
    ok(await p.locator('.pgi.sel').nth(0).getAttribute('data-pk') !== null, `${scheme}: the open page is marked in the index`);
    await p.keyboard.press('k');
    await p.waitForTimeout(300);
    ok((await hash(p)) !== h1, `${scheme}: k goes back up`);
    await p.keyboard.press('[');
    await p.waitForTimeout(200);
    ok(!(await p.isVisible('.pgidx')), `${scheme}: [ hides the index`);
    await p.keyboard.press('[');
    await p.waitForTimeout(200);
    ok(await p.isVisible('.pgidx'), `${scheme}: [ brings it back`);
    await p.keyboard.press('0');
    await p.waitForTimeout(600);
    ok((await hash(p)).startsWith('#/g/all'), `${scheme}: alt 0 shows every bay`);
    ok(await p.locator('.pgidx .grp').count() > 1, `${scheme}: grouped by bay`);
    await p.screenshot({ path: `${OUT}pages-all-1400-${scheme}.png` });
    await p.keyboard.press('0');
    await p.waitForTimeout(600);
    ok((await hash(p)).startsWith(`#/g/${bay}`), `${scheme}: alt 0 again returns to the bay`);
    await p.locator('.pghd .kb', { hasText: 'Copy link' }).click();
    await p.waitForTimeout(200);
    ok(await p.locator('.toast', { hasText: 'Link copied' }).count() === 1, `${scheme}: Copy link says so`);
    const pageName = await p.locator('.pghd .where').textContent();
    await p.keyboard.press('Backslash');
    await p.waitForTimeout(2500);
    const ho = await hash(p);
    if (ho.startsWith('#/s/')) {
      ok(ho.includes('/p/') && await p.isVisible('.ppane .pbar'), `${scheme}: o opens the page beside its session`);
      await p.screenshot({ path: `${OUT}page-1400-${scheme}.png` });
      await p.locator('.pbar .kb', { hasText: 'In Pages' }).click();
      await p.waitForTimeout(800);
      ok((await hash(p)).startsWith('#/g/'), `${scheme}: In Pages returns to the Pages view`);
    } else ok(true, `${scheme}: o skipped, the page's session is not running (${pageName})`);
    const first = await p.evaluate(() => fetch('/api/pages').then((r) => r.json()).then((l) => l.find((x) => x.kind === 'html')));
    await p.goto(`${base}/#/p/${first.session}/${encodeURIComponent(first.name)}`);
    await p.waitForTimeout(2500);
    ok(await p.isVisible('.palone .ppane .pbar'), `${scheme}: #/p/<session>/<name> still opens the page alone`);
    await p.screenshot({ path: `${OUT}pages-alone-1400-${scheme}.png` });
    const at = Math.max(Date.parse(first.updated || 0) || 0, Date.parse(first.shown || 0) || 0);
    await p.evaluate(([k, t]) => { const m = JSON.parse(localStorage.getItem('atc.pages.seen') || '{}'); m[k] = t; localStorage.setItem('atc.pages.seen', JSON.stringify(m)); }, [`${first.session}/${first.name}`, at - 600000]);
    await p.goto(`${base}/#/g/all/${first.session}/${encodeURIComponent(first.name)}`);
    await p.reload();
    await p.waitForTimeout(2500);
    const changes = p.locator('.pghd .kb', { hasText: 'Changes' });
    ok(await changes.count() === 1 && /updated .*, seen /.test(await p.locator('.pghd .l2').textContent()), `${scheme}: an updated page offers Changes and says when it was seen`);
    await p.keyboard.press('d');
    await p.waitForTimeout(200);
    ok(await changes.getAttribute('aria-pressed') === 'false', `${scheme}: d turns the change marks off`);
    await p.screenshot({ path: `${OUT}pages-updated-1400-${scheme}.png` });
    ok(!errs.length, `${scheme}: no page errors ${errs.join(' | ')}`);
    await ctx.close();
  }
  for (const scheme of ['light', 'dark']) {
    const ph = await b.newContext({ viewport: { width: 400, height: 860 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2, colorScheme: scheme });
    await ph.addInitScript(() => { try { localStorage.setItem('atc.notifask', '1'); } catch {} });
    const q = await ph.newPage();
    const errs = [];
    q.on('pageerror', (e) => (e.stack || '').includes('/api/sessions/') || errs.push(e.message));
    await stub(q);
    await q.goto(`${base}/#/g/${bay}`);
    await q.waitForTimeout(3000);
    ok(await q.isVisible('.pgi') && !(await q.isVisible('.pgread')), `${scheme} phone: the index is the screen`);
    await q.screenshot({ path: `${OUT}pages-400-${scheme}.png` });
    await q.locator('.pgi').first().tap();
    await q.waitForTimeout(2000);
    ok(await q.isVisible('.pgread') && !(await q.isVisible('.pgidx')), `${scheme} phone: a tap opens the page full screen`);
    ok(await q.isVisible('.pghd .more') && !(await q.isVisible('.pghd .kb.danger')), `${scheme} phone: one Actions button`);
    await q.screenshot({ path: `${OUT}pagefull-400-${scheme}.png` });
    await q.locator('.pghd .more button').tap();
    await q.waitForTimeout(300);
    await q.screenshot({ path: `${OUT}pageacts-400-${scheme}.png` });
    await q.locator('.pghd .more button').first().tap();
    await q.locator('.pghd .back').tap();
    await q.waitForTimeout(500);
    ok(await q.isVisible('.pgi'), `${scheme} phone: Back returns to the index`);
    ok(!errs.length, `${scheme} phone: no page errors ${errs.join(' | ')}`);
    await ph.close();
  }
  await b.close();
})();
