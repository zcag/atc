const { chromium } = require('/home/user/proj/ui-kit/node_modules/playwright-core');
const exe = '/home/user/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome';
const base = process.argv[2] || 'http://127.0.0.1:7299';
const OUT = __dirname + '/../../shots/build/';
const ok = (c, m) => console.log(c ? 'ok  ' : 'FAIL', m);
const stub = (p) => p.route('**/api/**', (r) => r.request().method() === 'GET' ? r.continue() : r.fulfill({ status: 204 }));
(async () => {
  const b = await chromium.launch({ executablePath: exe });
  const ctx = await b.newContext({ viewport: { width: 1400, height: 900 } });
  await ctx.addInitScript(() => { try { localStorage.setItem('atc.notifask', '1'); localStorage.removeItem('atc.project'); } catch {} });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await stub(p);
  await p.goto(base + '/');
  await p.waitForTimeout(3000);
  const cts = p.locator('.bays .cts').first();
  if (await cts.count()) {
    await cts.click();
    await p.waitForTimeout(300);
    ok(await p.isVisible('.peek'), 'clicking a bay\'s counts peeks at it');
    await p.screenshot({ path: `${OUT}s4-peek-1400-light.png` });
    await p.keyboard.press('Escape');
    await p.waitForTimeout(200);
    ok(!(await p.isVisible('.peek')), 'esc closes the peek');
    await p.keyboard.press('Shift+Alt+1');
    await p.waitForTimeout(300);
    ok(await p.isVisible('.peek'), 'shift alt 1 peeks at bay 1');
    await p.keyboard.press('Escape');
  }
  const rows = await p.locator('.bview .brow').count();
  ok(rows > 0, `board shows ${rows} rows`);
  ok(await p.isVisible('.pindex'), 'page index beside the board');
  const first = p.locator('.bview .brow').first();
  await first.click({ position: { x: 600, y: 10 } });
  await p.waitForTimeout(200);
  ok(await p.isVisible('.bexp'), 'a click opens the row in place');
  await first.click({ position: { x: 600, y: 10 } });
  await p.waitForTimeout(200);
  ok(!(await p.isVisible('.bexp')), 'a second click folds it');
  await p.keyboard.press('BracketRight');
  await p.waitForTimeout(200);
  ok(!(await p.isVisible('.pindex')), '] hides the page index');
  await p.keyboard.press('BracketRight');
  await p.keyboard.press('j');
  await p.waitForTimeout(200);
  ok(await p.locator('.brow.cur').count() === 1, 'j selects a row');
  await p.keyboard.press(' ');
  await p.waitForTimeout(200);
  ok(await p.isVisible('.bexp'), 'space opens the selected row');
  await p.keyboard.press('Enter');
  await p.waitForTimeout(800);
  ok(await p.evaluate(() => location.hash.startsWith('#/s/')), 'enter opens the session');
  ok(await p.locator('.rail .brow').count() > 0, 'the rail lists the bay beside the session');
  await p.screenshot({ path: `${OUT}s4-rail-1400-light.png` });
  const other = p.locator('.rail .brow:not(.sel)').first();
  if (await other.count()) {
    const sid = await other.getAttribute('data-sid');
    await other.click();
    await p.waitForTimeout(600);
    ok(await p.evaluate((s) => location.hash.includes(s.slice(0, 8)), sid), 'a rail row opens its session');
  }
  ok(!errs.length, 'no page errors ' + errs.join(' | '));
  await ctx.close();
  const ph = await b.newContext({ viewport: { width: 400, height: 860 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  await ph.addInitScript(() => { try { localStorage.removeItem('atc.project'); } catch {} });
  const q = await ph.newPage();
  await stub(q);
  await q.goto(base + '/');
  await q.waitForTimeout(3000);
  await q.locator('.bview .brow').first().tap();
  await q.waitForTimeout(300);
  ok(await q.isVisible('.bexp'), 'phone: a tap opens the row');
  await q.screenshot({ path: `${OUT}s4-open-400-light.png` });
  await q.locator('.bexp .btn', { hasText: 'Open' }).first().tap();
  await q.waitForTimeout(800);
  ok(await q.evaluate(() => location.hash.startsWith('#/s/')), 'phone: Open goes to the session');
  await b.close();
})();
