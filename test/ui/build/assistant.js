const { chromium } = require('/home/user/proj/ui-kit/node_modules/playwright-core');
const fs = require('fs');
const exe = '/home/user/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome';
const base = process.argv[2] || 'http://127.0.0.1:7299';
const OUT = __dirname + '/../../shots/build/';
const FAKE = fs.readFileSync(__dirname + '/fakecall.js', 'utf8');
const SILENCE = (() => { const n = 8000 * 4, b = Buffer.alloc(44 + n); b.write('RIFF', 0); b.writeUInt32LE(36 + n, 4); b.write('WAVEfmt ', 8); b.writeUInt32LE(16, 16); b.writeUInt16LE(1, 20); b.writeUInt16LE(1, 22); b.writeUInt32LE(8000, 24); b.writeUInt32LE(8000, 28); b.writeUInt16LE(1, 32); b.writeUInt16LE(8, 34); b.write('data', 36); b.writeUInt32LE(n, 40); b.fill(128, 44); return b; })();
let fails = 0;
const ok = (c, m) => { if (!c) fails++; console.log(c ? 'ok  ' : 'FAIL', m); };
const posts = [];
const prep = async (ctx) => {
  await ctx.addInitScript(() => { try { localStorage.setItem('atc.notifask', '1'); localStorage.removeItem('atc.panes'); } catch {} });
  await ctx.route('**/call.js', (r) => r.fulfill({ status: 200, contentType: 'text/javascript', body: FAKE }));
  await ctx.route('**/api/**', (r) => {
    if (r.request().method() === 'GET') return r.continue();
    posts.push(r.request().method() + ' ' + new URL(r.request().url()).pathname);
    return r.fulfill({ status: 204 });
  });
  await ctx.route('**/api/call/voices/sample**', (r) => r.fulfill({ status: 200, contentType: 'audio/wav', body: SILENCE }));
};
const desk = (b, scheme) => b.newContext({ viewport: { width: 1400, height: 900 }, colorScheme: scheme, permissions: ['microphone'] });
const phone = (b, scheme) => b.newContext({ viewport: { width: 400, height: 860 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2, colorScheme: scheme, permissions: ['microphone'] });
const wait = (p, ms = 400) => p.waitForTimeout(ms);
const hash = (p) => p.evaluate(() => location.hash);

(async () => {
  const sessions = await (await fetch(base + '/api/sessions')).json();
  const other = sessions.find((s) => s.kind !== 'hub' && s.attachable && ['working', 'your-turn'].includes(s.state));
  const b = await chromium.launch({ executablePath: exe, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
  for (const scheme of ['light', 'dark']) {
    const ctx = await desk(b, scheme);
    await prep(ctx);
    const p = await ctx.newPage();
    const errs = [];
    p.on('pageerror', (e) => errs.push(e.message));
    await p.goto(base + '/');
    await wait(p, 3000);
    await p.keyboard.press('.');
    await wait(p, 1500);
    ok(await hash(p) === '#/assist', `${scheme}: . opens the assistant`);
    ok(await p.isVisible('.assistv .ahd h1'), 'the header says Assistant');
    ok(await p.isVisible('.aleft'), 'Touched today is beside it');
    ok(await p.isVisible('.assistv .tx-wrap'), 'its conversation is the transcript');
    ok(!(await p.isVisible('.console')), 'no console line under the assistant');
    ok(await p.isVisible('.assistv .box .apr'), 'the composer starts with assistant>');
    await p.screenshot({ path: `${OUT}assistant-1400-${scheme}.png` });
    await p.keyboard.press('[');
    await wait(p);
    ok(!(await p.isVisible('.aleft')), '[ hides the left pane');
    await p.keyboard.press('[');
    await wait(p);
    ok(await p.isVisible('.aleft'), '[ shows it again');

    await p.keyboard.down('.');
    await wait(p, 120);
    await p.keyboard.up('.');
    await wait(p, 900);
    ok(await p.evaluate(() => window.__dialed === 1), '. again starts a call');
    ok(await p.isVisible('.callp'), 'the call docks on the right');
    ok(await p.evaluate(() => document.querySelector('.callp').getBoundingClientRect().width === 380), 'the panel is 380px');
    ok(!(await p.isVisible('.callp .caps')), 'no captions over the assistant');
    ok(!(await p.isVisible('.aleft')), 'the left pane steps aside for the call');
    ok(await p.isVisible('.assistv .box .apr.call .oncall'), 'the composer says On a call');
    ok(!(await p.isVisible('.assistv .box .ctrace')), 'no moving line while the persona is on screen');
    await p.screenshot({ path: `${OUT}call-1400-${scheme}.png` });
    await p.keyboard.press('m');
    await wait(p);
    ok(await p.evaluate(() => window.__call && document.querySelector('.ctl .btn[aria-pressed="true"]')?.textContent.startsWith('Unmute')), 'm mutes');
    await p.keyboard.press('m');
    await p.locator('.callp .ctl .btn', { hasText: 'Character' }).click();
    await wait(p, 1500);
    ok(await p.isVisible('.callp .picks'), 'Character opens the picker inside the panel');
    ok(await p.isVisible('.callp .cpers'), 'the big character stays above it as the preview');
    const chars = await p.locator('.picks .pick').count();
    ok(chars >= 2, `it lists ${chars} characters`);
    const other = p.locator('.picks .pick[aria-checked="false"]').first();
    const name = await other.locator('b').textContent();
    await other.click();
    await wait(p, 600);
    ok(await p.evaluate(() => document.querySelector('.picks .pick[aria-checked="true"] b').textContent) === name, `picking ${name} takes at once`);
    await p.locator('.picks .pick', { hasText: 'orb' }).first().click();
    const vrows = await p.locator('.picks .vpick').count();
    ok(vrows > 0, `it lists ${vrows} voices`);
    if (vrows) {
      const play = p.locator('.picks .vpick .kb', { hasText: 'Play' }).first();
      await play.click();
      await wait(p, 500);
      ok(await p.locator('.picks .vpick .kb[aria-pressed="true"]').count() === 1, 'Play plays the sample and turns into Stop ' + (await p.locator('.picks .sub').allTextContents()).join());
    }
    await p.screenshot({ path: `${OUT}callpicks-1400-${scheme}.png` });
    await p.keyboard.press('Escape');
    await wait(p);
    ok(!(await p.isVisible('.callp .picks')) && await p.isVisible('.callp'), 'esc closes the picker, the call stays');
    await p.keyboard.press('Escape');
    await wait(p);
    ok(!(await p.isVisible('.callp')), 'esc minimizes the call');
    ok(await p.isVisible('.assistv .box .ctrace'), 'minimized: the line moves in the composer');
    await p.keyboard.press('.');
    await wait(p);
    ok(await p.isVisible('.callp'), '. returns to the call');

    if (other) {
      await p.evaluate((id) => (location.hash = `#/s/${id}`), other.id || other.sessionId);
      await wait(p, 2500);
      ok(await p.isVisible('.callp .caps'), 'over a session the panel has captions');
      ok(await p.isVisible('.console.callline'), 'the console line says on a call');
      ok(!(await p.isVisible('.console.callline .ctrace')), 'no moving line there while the panel shows');
      await p.screenshot({ path: `${OUT}callover-1400-${scheme}.png` });
      await p.locator('.callp .cph .kb', { hasText: 'Minimize' }).click();
      await wait(p, 600);
      ok(await p.isVisible('.console.callline .ctrace'), 'minimized: the console line carries the live line');
      const px = () => p.evaluate(() => document.querySelector('.console .ctrace').toDataURL());
      const h1 = await px();
      await wait(p, 300);
      const h2 = await px();
      ok(h1 !== h2, 'the line follows the call\'s levels');
      await p.screenshot({ path: `${OUT}callpill-1400-${scheme}.png` });
      await p.locator('.console.callline .back').click();
      await wait(p);
      ok(await p.isVisible('.callp'), 'clicking the line returns to the call');
    }
    await p.keyboard.press('Shift+E');
    await wait(p, 500);
    ok(await p.evaluate(() => window.__hungup === 1), 'shift e ends the call');
    await wait(p, 2800);
    ok(!(await p.isVisible('.callp')), 'the ended call leaves');
    ok(!(await p.isVisible('.console.callline')), 'the console line is back');

    await p.evaluate(() => (location.hash = '#/assist'));
    await wait(p, 1200);
    ok(await hash(p) === '#/assist', 'and stays in the assistant');
    await p.keyboard.press('Escape');
    await wait(p, 500);
    ok(await hash(p) !== '#/assist', 'esc again closes the assistant');
    ok(!errs.length, 'no page errors ' + errs.join(' | '));
    await ctx.close();
  }

  for (const scheme of ['light', 'dark']) {
    const ctx = await phone(b, scheme);
    await prep(ctx);
    const q = await ctx.newPage();
    const errs = [];
    q.on('pageerror', (e) => errs.push(e.message));
    await q.goto(base + '/#/assist');
    await wait(q, 3500);
    ok(await q.isVisible('.assistv .tx-wrap'), `${scheme} phone: the assistant opens`);
    ok(!(await q.isVisible('.aleft')), 'phone: no left pane');
    ok(await q.locator('.tabbar .on', { hasText: 'Assistant' }).count() === 1, 'phone: the Assistant tab is on');
    await q.screenshot({ path: `${OUT}assistant-400-${scheme}.png` });
    await q.locator('.ahd .kb', { hasText: 'Today' }).tap();
    await wait(q, 500);
    ok(await q.isVisible('.asheet .aleft'), 'phone: Today opens touched today as a sheet');
    await q.screenshot({ path: `${OUT}assistant-today-400-${scheme}.png` });
    await q.reload();
    await wait(q, 3500);
    await q.evaluate(() => (location.hash = '#/call'));
    await wait(q, 800);
    ok(await q.isVisible('.callp.full'), 'phone: #/call is the call, full screen');
    await q.locator('.callp .ctl .btn', { hasText: 'Character' }).tap();
    await wait(q, 1500);
    ok(await q.isVisible('.callp .picks'), 'phone: Character opens the picker before calling');
    await q.screenshot({ path: `${OUT}callpicks-400-${scheme}.png` });
    await q.locator('.picks .pkh .kb').tap();
    await wait(q, 300);
    await q.locator('.callp .ctl .btn', { hasText: 'Call the assistant' }).tap();
    await wait(q, 1000);
    ok(await q.evaluate(() => window.__dialed === 1), 'phone: Call the assistant dials');
    ok(await q.isVisible('.callp.full .caps'), 'phone: the call has captions');
    ok(await q.isVisible('.tabbar'), 'phone: the tab bar stays under the call');
    await q.screenshot({ path: `${OUT}call-400-${scheme}.png` });
    await q.locator('.callp .cph .kb', { hasText: 'Minimize' }).tap();
    await wait(q, 800);
    ok(!(await q.isVisible('.callp')), 'phone: Minimize leaves the call screen');
    ok(await q.isVisible('.callpill'), 'phone: the pill sits above the tab bar');
    const pill = await q.evaluate(() => { const a = document.querySelector('.callpill').getBoundingClientRect(), t = document.querySelector('.tabbar').getBoundingClientRect(); return [a.height, Math.round(t.top - a.bottom)]; });
    ok(pill[0] >= 44 && Math.abs(pill[1]) <= 1, `phone: 44px, right on the tab bar (${pill})`);
    await q.screenshot({ path: `${OUT}callpill-400-${scheme}.png` });
    await q.locator('.callpill .back').tap();
    await wait(q, 600);
    ok(await hash(q) === '#/call', 'phone: tapping the pill returns to the call');
    await q.locator('.callp .ctl .btn.end').tap();
    await wait(q, 2200);
    ok(await hash(q) !== '#/call', 'phone: the ended call closes itself');
    ok(!errs.length, 'phone: no page errors ' + errs.join(' | '));
    await ctx.close();
  }
  const bad = posts.filter((x) => !/^POST \/api\/(assist|seen|drafts|bays|term|presence)/.test(x) && !/^(PUT|PATCH) \/api\/(seen|drafts|bays)/.test(x));
  ok(!bad.length, 'only expected writes were attempted (all stubbed) ' + bad.join(', '));
  await b.close();
  process.exitCode = fails ? 1 : 0;
})();
